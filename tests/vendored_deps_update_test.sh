printf '{"packages":[{"name":"foo/bar","version":"1.0.0","source":{"url":"https://github.com/old/bar.git","reference":"abc"},"dist":{"url":"https://api.github.com/repos/old/bar/zipball/abc","reference":"abc"}}]}\n' > "$dir/composer.lock"
