failures=()

PROXY='<?php
/* this file was generated by the matomo-scoper tool */
'

# A committed plugin whose tree is correct, then an updated lock and a rescoped file on top.
make_plugin() {
  local dir="$WORK/$1"
  rm -rf "$dir"
  mkdir -p "$dir/vendor/prefixed/foo/src" "$dir/vendor/prefixed/vendor/composer"
  printf '%s' "$PROXY" > "$dir/vendor/autoload.php"
  printf '<?php\nnamespace Matomo\\Dependencies\\Foo\\Bar;\n' > "$dir/vendor/prefixed/foo/src/Bar.php"
  printf '<?php\nnamespace Composer\\Autoload;\n' > "$dir/vendor/prefixed/vendor/composer/ClassLoader.php"
  printf '{"content-hash":"a","packages":[{"name":"foo/bar","version":"1.0.0"}]}\n' > "$dir/composer.lock"
  git -C "$dir" init -q
  git -C "$dir" add composer.lock vendor
  git -C "$dir" -c user.email=t@t -c user.name=t commit -qm base
  printf '{"content-hash":"b","packages":[{"name":"foo/bar","version":"1.1.0"}]}\n' > "$dir/composer.lock"
  printf '<?php\nnamespace Matomo\\Dependencies\\Foo\\Bar;\n// 1.1.0\n' > "$dir/vendor/prefixed/foo/src/Bar.php"
  echo "$dir"
}

expect() {
  local description="$1" want="$2" dir="$3" pattern="$4"
  shift 4
  tests=$((tests + 1))
  local output status
  output=$(bash "$CHECK" "$dir" Foo "$@" 2>&1)
  status=$?
  if [ "$status" -ne "$want" ]; then
    echo "FAIL - $description (exited $status, wanted $want): $output"
    failures+=("$description")
  elif [ -n "$pattern" ] && ! printf '%s' "$output" | grep -q -- "$pattern"; then
    echo "FAIL - $description (output did not match $pattern): $output"
    failures+=("$description")
  else
    echo "ok - $description"
  fi
}

