expect_annotations() {
  local description="$1" dir="$2" want="$3"
  tests=$((tests + 1))
  local count
  count=$(bash "$CHECK" "$dir" Foo 'Composer\Autoload' 2>&1 | grep -c '^::warning file=')
  if [ "$count" -ne "$want" ]; then
    echo "FAIL - $description ($count annotations, wanted $want)"
    failures+=("$description")
  else
    echo "ok - $description"
  fi
}
