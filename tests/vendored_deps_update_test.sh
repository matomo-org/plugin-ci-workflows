#!/bin/bash
# Tests for scripts/bash/check_scoped_tree.sh, the scope-dependencies action and
# .github/workflows/plugin-vendored-deps-update.yml.
# Usage: bash tests/vendored_deps_update_test.sh
#
# The check exists because the scoping pipeline reports success on output it did not produce, so
# every tree case here is one that looks finished and is not.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
CHECK="$ROOT/scripts/bash/check_scoped_tree.sh"
WORKFLOW="$ROOT/.github/workflows/plugin-vendored-deps-update.yml"
ACTION="$ROOT/actions/scope-dependencies/action.yml"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

tests=0
failures=()

PROXY='<?php
/* this file was generated by the matomo-scoper tool */
'

# A committed plugin whose tree is correct, then an updated lock and a rescoped file on top.
make_plugin() {
  local dir="$WORK/$1"
  rm -rf "$dir"
  mkdir -p "$dir/vendor/prefixed/foo/src" "$dir/vendor/prefixed/vendor/composer"
  printf '%s' "$PROXY" > "$dir/vendor/autoload.php"
  printf '<?php\nnamespace Matomo\\Dependencies\\Foo\\Bar;\n' > "$dir/vendor/prefixed/foo/src/Bar.php"
  printf '<?php\nnamespace Composer\\Autoload;\n' > "$dir/vendor/prefixed/vendor/composer/ClassLoader.php"
  printf '{"content-hash":"a","packages":[{"name":"foo/bar","version":"1.0.0"}]}\n' > "$dir/composer.lock"
  git -C "$dir" init -q
  git -C "$dir" add composer.lock vendor
  git -C "$dir" -c user.email=t@t -c user.name=t commit -qm base
  printf '{"content-hash":"b","packages":[{"name":"foo/bar","version":"1.1.0"}]}\n' > "$dir/composer.lock"
  printf '<?php\nnamespace Matomo\\Dependencies\\Foo\\Bar;\n// 1.1.0\n' > "$dir/vendor/prefixed/foo/src/Bar.php"
  echo "$dir"
}

expect() {
  local description="$1" want="$2" dir="$3" pattern="$4"
  shift 4
  tests=$((tests + 1))
  local output status
  output=$(bash "$CHECK" "$dir" Foo "$@" 2>&1)
  status=$?
  if [ "$status" -ne "$want" ]; then
    echo "FAIL - $description (exited $status, wanted $want): $output"
    failures+=("$description")
  elif [ -n "$pattern" ] && ! printf '%s' "$output" | grep -q -- "$pattern"; then
    echo "FAIL - $description (output did not match $pattern): $output"
    failures+=("$description")
  else
    echo "ok - $description"
  fi
}

dir=$(make_plugin good)
expect "a rescoped tree passes" 0 "$dir" '' 'Composer\Autoload'

expect "Composer's autoloader namespace fails when it is not allowed" 1 "$dir" 'Composer\\Autoload, outside'

dir=$(make_plugin stock-autoload)
printf '<?php\n// autoload.php @generated by Composer\n' > "$dir/vendor/autoload.php"
expect "the stock Composer autoloader in place of the proxy fails" 1 "$dir" 'not the matomo-scoper proxy' 'Composer\Autoload'

dir=$(make_plugin unprefixed)
printf '<?php\nnamespace GuzzleHttp\\Psr7;\n' > "$dir/vendor/prefixed/foo/src/Leak.php"
expect "a file the scoper copied through unprefixed fails" 1 "$dir" 'namespace GuzzleHttp\\Psr7, outside' 'Composer\Autoload'

dir=$(make_plugin lookalike)
printf '<?php\nnamespace ComposerX\\Thing;\n' > "$dir/vendor/prefixed/foo/src/Lookalike.php"
expect "an allowed namespace does not also allow one that merely starts with its name" 1 "$dir" 'ComposerX\\Thing' 'Composer'

dir=$(make_plugin digits)
printf '<?php\nnamespace Matomo\\Dependencies\\Foo\\V2;\nnamespace ComposerV2\\X;\n' > "$dir/vendor/prefixed/foo/src/V2.php"
expect "a namespace containing digits is read whole" 1 "$dir" 'namespace ComposerV2\\X, outside' 'Composer\Autoload'

dir=$(make_plugin other-plugin)
printf '<?php\nnamespace Matomo\\Dependencies\\FooBar\\X;\n' > "$dir/vendor/prefixed/foo/src/X.php"
expect "another plugin's prefix is not this plugin's" 1 "$dir" 'FooBar' 'Composer\Autoload'

dir=$(make_plugin stale)
git -C "$dir" checkout -q -- vendor/prefixed
expect "a new lock over the old prefixed tree fails" 1 "$dir" 'is stale' 'Composer\Autoload'

dir=$(make_plugin metadata-only)
git -C "$dir" checkout -q -- vendor/prefixed
printf '{"content-hash":"c","packages":[{"name":"foo/bar","version":"1.0.0"}]}\n' > "$dir/composer.lock"
expect "a lock that changed only its metadata does not need a new tree" 0 "$dir" '' 'Composer\Autoload'

dir=$(make_plugin new-file-only)
git -C "$dir" checkout -q -- vendor/prefixed
printf '<?php\nnamespace Matomo\\Dependencies\\Foo\\New;\n' > "$dir/vendor/prefixed/foo/src/New.php"
expect "a tree whose only change is a new file counts as regenerated" 0 "$dir" '' 'Composer\Autoload'

dir=$(make_plugin empty)
rm -rf "$dir/vendor/prefixed"/*
expect "a prefixed tree with no namespaces at all fails" 1 "$dir" 'no namespace declarations' 'Composer\Autoload'

# The action's downgrade target, run from the action's own step so the test cannot drift from it.
RESOLVE="$WORK/resolve.sh"
python3 - "$ACTION" > "$RESOLVE" <<'PY'
import sys
import yaml

steps = yaml.safe_load(open(sys.argv[1]))['runs']['steps']
print([s for s in steps if s.get('id') == 'resolve'][0]['run'])
PY

expect_downgrade() {
  local description="$1" matomo_constraint="$2" input="$3" want="$4"
  tests=$((tests + 1))
  local dir="$WORK/downgrade" got
  rm -rf "$dir"
  mkdir -p "$dir"
  if [ -n "$matomo_constraint" ]; then
    jq -n --arg c "$matomo_constraint" '{name: "Foo", require: {matomo: $c}}' > "$dir/plugin.json"
  else
    echo '{"name": "Foo"}' > "$dir/plugin.json"
  fi
  : > "$WORK/output"
  if ! PLUGIN_PATH="$dir" DOWNGRADE_INPUT="$input" GITHUB_OUTPUT="$WORK/output" bash -e "$RESOLVE" > /dev/null 2>&1; then
    got=error
  else
    got=$(sed -n 's/^downgrade=//p' "$WORK/output")
  fi
  if [ "$got" = "$want" ]; then
    echo "ok - $description"
  else
    echo "FAIL - $description (got '$got', wanted '$want')"
    failures+=("$description")
  fi
}

expect_downgrade "a Matomo 6 plugin is transpiled to 8.1" '>=6.0.0-b1,<7.0.0-b1' auto 8.1
expect_downgrade "a Matomo 5 plugin is transpiled to 7.3" '>=5.0.0-b1,<6.0.0-b1' auto 7.3
expect_downgrade "a plugin that spans Matomo 5 and 6 is transpiled for 5" '>=5.0.0,<7.0.0-b1' auto 7.3
expect_downgrade "a plugin with no Matomo requirement gets the lower target" '' auto 7.3
expect_downgrade "none skips Rector" '>=6.0.0-b1,<7.0.0-b1' none ''
expect_downgrade "an explicit target overrides plugin.json" '>=6.0.0-b1,<7.0.0-b1' 7.3 7.3
expect_downgrade "a target the Rector config does not know fails" '>=6.0.0-b1,<7.0.0-b1' 8.2 error

# The guards the check leans on. Each of these has a failure that looks like success.
yaml_output=$(python3 - "$WORKFLOW" "$ACTION" <<'PY' 2>&1
import sys
import yaml

workflow = yaml.safe_load(open(sys.argv[1]))
steps = workflow['jobs']['update']['steps']
action_steps = yaml.safe_load(open(sys.argv[2]))['runs']['steps']

def check(description, condition):
    print(("ok - " if condition else "FAIL - ") + description)

def step(name, within=steps):
    found = [s for s in within if s.get('name') == name]
    assert len(found) == 1, f"expected one step named {name!r}, found {len(found)}"
    return found[0]

def code(s):
    return '\n'.join(l for l in s['run'].splitlines() if not l.lstrip().startswith('#'))

for name in ('Scope', 'Downgrade'):
    check(f"Xdebug is off for the action's {name} step",
          str(step(name, action_steps).get('env', {}).get('XDEBUG_MODE')) == 'off')
check("the action checks php-scoper.phar actually runs",
      'php-scoper.phar" --version' in code(step('Scope', action_steps)))
check("the action checks the tree after everything that writes to it",
      action_steps[-1].get('name') == 'Check the scoped tree')

check("setup-php loads no coverage driver", step('Setup PHP')['with'].get('coverage') == 'none')

scope = step('Scope, downgrade and check')
this_repo = step('Check out plugin-ci-workflows repository')
check("the action comes from the checkout at workflows-ref, not a fixed ref",
      scope['uses'] == './.plugin-ci-workflows/actions/scope-dependencies'
      and this_repo['with']['path'] == '.plugin-ci-workflows'
      and this_repo['with']['ref'] == '${{ inputs.workflows-ref }}')

order = [s.get('name') for s in steps]
check("the tree is checked before the pull request is opened",
      order.index('Scope, downgrade and check') < order.index('Open or update the pull request'))

checkouts = [s for s in steps if str(s.get('uses', '')).startswith('actions/checkout@')]
check("no checkout leaves credentials in a git config the scoped tree is committed next to",
      all(s.get('with', {}).get('persist-credentials') is False for s in checkouts))

pr = step('Open or update the pull request')['with']
check("the workflow's commits are authored by the address the human-commit check filters on",
      '${{ env.BOT_EMAIL }}' in pr['author'] and '${{ env.BOT_EMAIL }}' in pr['committer'])
check("the human-commit check runs before anything is rebuilt",
      order.index('Check the update branch has no human commits') < order.index('Update dependencies'))
PY
)
yaml_status=$?
printf '%s\n' "$yaml_output"
while IFS= read -r line; do
  tests=$((tests + 1))
  case "$line" in
    "FAIL - "*) failures+=("${line#FAIL - }") ;;
  esac
done < <(printf '%s\n' "$yaml_output" | grep -E '^(ok|FAIL) - ')
# A traceback prints no FAIL line, so without this a renamed step would pass the suite having
# asserted nothing.
if [ "$yaml_status" -ne 0 ]; then
  tests=$((tests + 1))
  echo "FAIL - the workflow invariants block ran to completion (exited $yaml_status)"
  failures+=("the workflow invariants block ran to completion")
fi

echo
echo "$tests tests, ${#failures[@]} failures"
[ ${#failures[@]} -eq 0 ] || exit 1
